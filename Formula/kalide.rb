# frozen_string_literal: true

# Homebrew formula for `kalide` (macOS, Apple silicon and Intel).
#
# The tap is hosted in the source repository itself — `brew tap
# really-knows-ai/kalide <git url>` — so the tap root *is* this repo and
# `Formula/` is the tap's formula directory.
#
# `kalide` is distributed from the private repository really-knows-ai/kalide
# and both darwin/arm64 and darwin/amd64 binaries are built. The public
# release-download URLs below cannot be fetched anonymously, so each is
# resolved through the GitHub API by the custom strategy in lib/, using the
# user's HOMEBREW_GITHUB_API_TOKEN.
#
# ---------------------------------------------------------------------------
# REGENERATION CONTRACT (phase-9 task-5 release.yml manifest job)
# ---------------------------------------------------------------------------
# On every release the manifest job rewrites exactly version and TWO
# url/sha256 pairs (one per architecture) from the freshly published release,
# and nothing else:
#
#   1. version "X.Y.Z"                 <- the pushed tag, without the leading "v"
#   2. the `else` branch's url  .../download/vX.Y.Z/kalide-darwin-arm64
#      the `else` branch's sha256 "..." <- SHA-256 of kalide-darwin-arm64 as
#                                           printed in the release's checksums.txt
#   3. the `if Hardware::CPU.intel?` branch's url  .../download/vX.Y.Z/kalide-darwin-amd64
#      the `if Hardware::CPU.intel?` branch's sha256 "..." <- SHA-256 of
#                                           kalide-darwin-amd64 as printed in
#                                           the release's checksums.txt
#
# The asset names are fixed: `kalide-darwin-arm64` and `kalide-darwin-amd64`
# (see the Makefile `release` target). `depends_on :macos` / the strategy are
# not touched by regeneration.
#
# Requirement ACs (audited in release-0.5.0 phase-05 task-6):
#   - homebrew-install: kalide-darwin-arm64 (Apple silicon) or
#     kalide-darwin-amd64 (Intel) is fetched from the private release via the
#     same custom strategy using HOMEBREW_GITHUB_API_TOKEN, selected per the
#     running Mac's architecture; a missing or rejected token fails with a
#     clear message.
#   - tap-bucket-location: this file lives in the source repo's Formula/.
#   - package-manifest-update: version/url/sha256 follow the contract above.

require_relative "lib/github_private_release_download_strategy"

# Formula for the kalide single binary, fetched from the private release.
class Kalide < Formula
  desc "Markdown presentation tool"
  homepage "https://github.com/really-knows-ai/kalide"
  version "0.5.0"
  license "Apache-2.0"

  # PLACEHOLDER: url/sha256 pairs below are regenerated by the release
  # manifest job (phase-9 task-5) — see the regeneration contract above. Each
  # URL must stay in the release-download form so the custom strategy can
  # parse it.
  if Hardware::CPU.intel?
    url "https://github.com/really-knows-ai/kalide/releases/download/v0.5.0/kalide-darwin-amd64",
        using: GitHubPrivateReleaseDownloadStrategy
    sha256 "c021f968450e98ad7f7bf6fdb5ee60751fb113161fdb60616a37bc8b2dffeac3"
  else
    url "https://github.com/really-knows-ai/kalide/releases/download/v0.5.0/kalide-darwin-arm64",
        using: GitHubPrivateReleaseDownloadStrategy
    sha256 "0b2f6f657766c16ad88dfaa270c0b642735721a09e0b1c2c8334f5577aa1fdd0"
  end

  def install
    asset_name = Hardware::CPU.arm? ? "kalide-darwin-arm64" : "kalide-darwin-amd64"
    bin.install asset_name => "kalide"
  end

  def caveats
    <<~EOS
      kalide is a single self-contained binary. Run `kalide init` in an empty
      folder to create a starter deck, then `kalide start`.
    EOS
  end

  test do
    system bin/"kalide", "init"
    output = shell_output("#{bin}/kalide templates")
    assert_match(/\bhello\b/, output)
  end
end
